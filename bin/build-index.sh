#!/bin/bash
# build-index.sh — 技能索引骨架生成脚本
# 只提取 id + name + 文件大小，不提取描述
# desc 字段由 AI 第一次召唤时阅读全部 SKILL.md 后生成
# 用法: bash build-index.sh

SKILLS_DIR="${HOME}/.claude/skills"
OUTPUT="${SKILLS_DIR}/.skill-index.json"
[ -d "$SKILLS_DIR" ] || { echo "ERROR: $SKILLS_DIR not found"; exit 1; }

entries=""
count=0

for skill_dir in "$SKILLS_DIR"/*/; do
  [ -d "$skill_dir" ] || continue
  skill_id=$(basename "$skill_dir")
  skill_file="${skill_dir}SKILL.md"
  [ -f "$skill_file" ] || continue

  size_bytes=$(stat -c%s "$skill_file" 2>/dev/null || stat -f%z "$skill_file" 2>/dev/null || echo 0)
  if [ "$size_bytes" -lt 10000 ]; then size_est="small"
  elif [ "$size_bytes" -lt 30000 ]; then size_est="medium"
  elif [ "$size_bytes" -lt 60000 ]; then size_est="large"
  else size_est="xlarge"
  fi

  # 提取名称（第一个 # 或 ## 标题）
  heading=$(head -30 "$skill_file" 2>/dev/null | grep -m1 '^# \|^## ' | sed 's/^#* *//' | head -c 120)
  [ -z "$heading" ] && heading="$skill_id"

  # desc 留空，等待 AI 填充
  entry="{\"id\":\"${skill_id}\",\"name\":\"${heading}\",\"desc\":\"\",\"size\":\"${size_est}\",\"bytes\":${size_bytes}}"
  [ -n "$entries" ] && entries="${entries},"
  entries="${entries}${entry}"
  count=$((count + 1))
done

cat > "$OUTPUT" << EOF
{
  "version": 4,
  "generated_at": "$(date -u +%Y-%m-%dT%H:%M:%SZ)",
  "count": ${count},
  "needs_ai_desc": true,
  "skills": [${entries}]
}
EOF

echo "[OK] Index skeleton generated: ${OUTPUT} (${count} skills, $(wc -c < "$OUTPUT" 2>/dev/null | tr -d ' ') bytes)"
echo "[INFO] Descriptions will be generated by AI on first invocation"
